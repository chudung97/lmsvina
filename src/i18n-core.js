const vietnameseLetters = /[À-ỹĐđ]/

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

// Pattern keys use {0}, {1}… for values inserted at runtime; each value is translated too.
const compiledPatterns = extraPatterns.map(([source, en, ko]) => {
  const pieces = source.split(/\{(\d+)\}/)
  const order = []
  let expression = '^'
  pieces.forEach((piece, index) => {
    if (index % 2) {
      order.push(Number(piece))
      expression += '([\\s\\S]*?)'
    } else {
      expression += escapeRegExp(piece)
    }
  })
  const literals = pieces.filter((_, index) => index % 2 === 0)
  const literal = [...literals].sort((a, b) => b.length - a.length)[0]
  const specificity = literals.join('').length
  return { regex: new RegExp(`${expression}$`), order, literal, specificity, targets: { en, ko } }
}).sort((a, b) => b.specificity - a.specificity)

const sortedFragments = Object.fromEntries(
  Object.entries(textFragments).map(([language, fragments]) => [
    language,
    Object.entries(fragments).sort(([sourceA], [sourceB]) => sourceB.length - sourceA.length),
  ]),
)

const translationCache = { en: new Map(), ko: new Map() }

function translateText(text, language, depth = 0) {
  if (typeof text !== 'string' || !text || !translations[language]) return text
  const cache = translationCache[language]
  const cached = cache.get(text)
  if (cached !== undefined) return cached
  if (Object.hasOwn(translations[language], text)) return translations[language][text]
  const core = text.trim()
  let result = text
  if (core) {
    const translated = translateCore(core, language, depth)
    if (translated !== core) {
      const leading = text.slice(0, text.indexOf(core))
      result = leading + translated + text.slice(leading.length + core.length)
    }
  }
  if (cache.size > 5000) cache.clear()
  cache.set(text, result)
  return result
}

function translateCore(text, language, depth) {
  const dictionary = translations[language]
  if (Object.hasOwn(dictionary, text)) return dictionary[text]
  if (!vietnameseLetters.test(text)) return text
  if (depth < 3) {
    for (const pattern of compiledPatterns) {
      if (!text.includes(pattern.literal)) continue
      const match = pattern.regex.exec(text)
      if (!match) continue
      return pattern.targets[language].replace(/\{(\d+)\}/g, (_, index) => {
        const value = match[pattern.order.indexOf(Number(index)) + 1] ?? ''
        return translateText(value, language, depth + 1)
      })
    }
  }
  if (language === 'en') {
    const repeated = text.match(/^Đã tạo (\d+) buổi họp lặp\.$/)
    if (repeated) return `Created ${repeated[1]} recurring meetings.`
    const createdUser = text.match(/^Đã tạo tài khoản (.+)\. Hãy gửi thông tin đăng nhập cho người dùng qua kênh riêng\.$/)
    if (createdUser) return `Account ${createdUser[1]} created. Share the login details with the user through a private channel.`
    const resetUser = text.match(/^Đã đặt lại mật khẩu cho (.+)\. Phiên đăng nhập hiện có của tài khoản đã bị thu hồi\.$/)
    if (resetUser) return `Password reset for ${resetUser[1]}. The account’s active sessions have been revoked.`
    const updatedUser = text.match(/^Đã cập nhật tên và email của (.+)\.$/)
    if (updatedUser) return `Name and email updated for ${updatedUser[1]}.`
    if (text === 'Đã lưu lịch họp.') return 'Meeting saved.'
  }
  if (language === 'ko') {
    const repeated = text.match(/^Đã tạo (\d+) buổi họp lặp\.$/)
    if (repeated) return `반복 회의 ${repeated[1]}개가 생성되었습니다.`
    const createdUser = text.match(/^Đã tạo tài khoản (.+)\. Hãy gửi thông tin đăng nhập cho người dùng qua kênh riêng\.$/)
    if (createdUser) return `${createdUser[1]} 계정이 생성되었습니다. 로그인 정보는 사용자에게 비공개 채널로 전달하세요.`
    const resetUser = text.match(/^Đã đặt lại mật khẩu cho (.+)\. Phiên đăng nhập hiện có của tài khoản đã bị thu hồi\.$/)
    if (resetUser) return `${resetUser[1]}의 비밀번호가 재설정되었습니다. 해당 계정의 활성 세션이 취소되었습니다.`
    const updatedUser = text.match(/^Đã cập nhật tên và email của (.+)\.$/)
    if (updatedUser) return `${updatedUser[1]}의 이름과 이메일이 업데이트되었습니다.`
  }
  return (sortedFragments[language] || []).reduce(
    (result, [source, target]) => result.replaceAll(source, target),
    text,
  )
}

const translatedAttributes = ['aria-label', 'placeholder', 'title', 'alt', 'label', 'data-label']
const localizedComponents = new WeakMap()

// Function components are rendered through a wrapper that localizes their output, so every
// screen nested under a LocalizedTree is translated without wrapping each component by hand.
function localizedComponent(Component) {
  let Localized = localizedComponents.get(Component)
  if (!Localized) {
    Localized = function LocalizedComponent(props) {
      const { language } = useLocale()
      return localize(Component(props), language)
    }
    Localized.displayName = Component.displayName || Component.name
    Localized.isLocalized = true
    localizedComponents.set(Component, Localized)
  }
  return Localized
}

function localize(node, language) {
  if (typeof node === 'string') return translateText(node, language)
  if (Array.isArray(node)) return Children.map(node, (child) => localize(child, language))
  if (!isValidElement(node)) return node

  const props = {}
  if (language !== 'vi') {
    for (const attribute of translatedAttributes) {
      if (typeof node.props[attribute] === 'string') {
        props[attribute] = translateText(node.props[attribute], language)
      }
    }
  }
  // An <option> without a value submits its text, which must stay untranslated.
  if (node.type === 'option' && node.props.value === undefined && typeof node.props.children === 'string') {
    props.value = node.props.children
  }
  if (node.props.children !== undefined) props.children = localize(node.props.children, language)

  const { type } = node
  if (typeof type === 'function' && !type.isLocalized && !type.prototype?.isReactComponent) {
    return createElement(localizedComponent(type), { ...node.props, ...props, key: node.key })
  }
  return cloneElement(node, props)
}


let dialogLanguage = 'vi'

export function setDialogLanguage(language) {
  dialogLanguage = language
}

export function translate(text, language = dialogLanguage) {
  return translateText(text, language)
}

// Native confirm/prompt/alert dialogs are outside React, so translate their message here.
export function installDialogTranslation(target = window) {
  for (const name of ['alert', 'confirm', 'prompt']) {
    const original = target[name]
    if (typeof original !== 'function' || original.isLocalized) continue
    const localized = function (message, ...rest) {
      const text = typeof message === 'string' ? translateText(message, dialogLanguage) : message
      return original.call(target, text, ...rest)
    }
    localized.isLocalized = true
    target[name] = localized
  }
}

